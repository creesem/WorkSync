"""Regenerate the NEXT-SESSION state block and check ticket-tracker hygiene.

The handoff's machine-checkable facts (HEAD, test status, open tickets, next
milestone) are generated into a marker-delimited block so they cannot drift from
reality. The prose around the block is left untouched.

Usage:
    python scripts/handoff.py status                 # print the ticket table
    python scripts/handoff.py check                  # exit 1 on stale/unknown statuses
    python scripts/handoff.py write [--with-tests]   # rewrite the generated block
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import Counter
from dataclasses import dataclass
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
V2 = REPO / ".scratch" / "worksync-platform-v2"
HANDOFF = V2 / "HANDOFF.md"
NEXT_SESSION = V2 / "NEXT-SESSION.md"
BEGIN = "<!-- BEGIN GENERATED:state (scripts/handoff.py) -->"
END = "<!-- END GENERATED:state -->"
SCAFFOLD = (
    "# WorkSync — generated handoff state\n"
    "\n"
    "Generated by `scripts/handoff.py`; do not edit by hand. Refresh with\n"
    "`python scripts/handoff.py write --with-tests`.\n"
    "\n"
    f"{BEGIN}\n"
    f"{END}\n"
)
DONE_STATUSES = frozenset({"done", "complete", "closed"})
KNOWN_STATUSES = frozenset({"ready-for-agent", "claimed", "in-progress", "blocked", *DONE_STATUSES})
ISSUE_GLOBS = ("*/issues/*.md", "issues/*.md")
MILESTONE_RE = re.compile(r"(\d{2}-[a-z0-9-]+)/")
STATUS_RE = re.compile(r"^\*\*Status:\*\*\s*(.+?)\s*$", re.MULTILINE)
CHECKBOX_RE = re.compile(r"^\s*-\s\[([ xX])\]", re.MULTILINE)


@dataclass(frozen=True)
class Ticket:
    """One tracker ticket parsed from its markdown file."""

    milestone: str
    number: str
    title: str
    status: str
    done_boxes: int
    total_boxes: int

    @property
    def ref(self) -> str:
        return f"{self.milestone}/{self.number}"

    @property
    def all_boxes_checked(self) -> bool:
        return self.total_boxes > 0 and self.done_boxes == self.total_boxes

    @property
    def open(self) -> bool:
        return self.status.casefold() not in DONE_STATUSES and not self.all_boxes_checked

    @property
    def stale(self) -> bool:
        """All boxes ticked but the status still says work is open."""
        return self.all_boxes_checked and self.status.casefold() not in DONE_STATUSES

    @property
    def unknown(self) -> bool:
        return self.status.casefold() not in KNOWN_STATUSES


def parse_ticket(path: Path, root: Path = V2) -> Ticket:
    """Parse one ticket file into a :class:`Ticket`."""
    text = path.read_text(encoding="utf-8")
    match = STATUS_RE.search(text)
    status = match.group(1).split()[0].strip() if match and match.group(1).split() else "unknown"
    boxes = CHECKBOX_RE.findall(text)
    done = sum(1 for box in boxes if box in "xX")
    relative = path.relative_to(root)
    milestone = relative.parts[0] if len(relative.parts) > 2 else "(root)"
    stem = path.stem
    number, _, slug = stem.partition("-")
    title = slug.replace("-", " ").strip() or stem
    return Ticket(milestone, number, title, status, done, len(boxes))


def discover_tickets(root: Path = V2) -> list[Ticket]:
    """Return every ticket under *root*, in stable order."""
    tickets: list[Ticket] = []
    seen: set[Path] = set()
    for pattern in ISSUE_GLOBS:
        for path in sorted(root.glob(pattern)):
            if path not in seen:
                seen.add(path)
                tickets.append(parse_ticket(path, root))
    return tickets


def active_milestone(path: Path = NEXT_SESSION) -> str | None:
    """Return the milestone named by NEXT-SESSION.md, or ``None``."""
    if not path.is_file():
        return None
    match = MILESTONE_RE.search(path.read_text(encoding="utf-8"))
    return match.group(1) if match else None


def _git(*args: str) -> str:
    result = subprocess.run(["git", "-C", str(REPO), *args], capture_output=True, text=True, check=False)
    return result.stdout.strip()


def _run_tests() -> str:
    result = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-n", "auto"],
        cwd=REPO,
        capture_output=True,
        text=True,
        check=False,
    )
    for line in reversed(result.stdout.splitlines()):
        if " passed" in line or " failed" in line or " error" in line:
            return line.strip()
    return "unknown (pytest produced no summary)"


def render_block(
    tickets: list[Ticket],
    *,
    sha: str,
    subject: str,
    today: str,
    tests: str | None = None,
    active: str | None = None,
) -> str:
    """Render the generated state block (without the marker lines)."""
    open_tickets = [ticket for ticket in tickets if ticket.open]
    if active:
        shown = [ticket for ticket in open_tickets if ticket.milestone == active]
        others = [ticket for ticket in open_tickets if ticket.milestone != active]
    else:
        shown, others = open_tickets, []
    lines = [
        f"- HEAD: `{sha}` {subject}".rstrip(),
        f"- Generated: {today}",
        f"- Tests: {tests or 'not run'}",
        f"- Open tickets: {len(open_tickets)} (active: {len(shown)})",
    ]
    for ticket in shown:
        lines.append(f"  - `{ticket.ref}` {ticket.status} — {ticket.done_boxes}/{ticket.total_boxes} — {ticket.title}")
    if others:
        counts = Counter(ticket.milestone for ticket in others)
        summary = ", ".join(f"{milestone} ({count})" for milestone, count in sorted(counts.items()))
        lines.append(f"- Other milestones (not shown): {summary}")
    lines.append(f"- Next milestone: {active or ', '.join(sorted({t.milestone for t in open_tickets})) or 'none'}")
    return "\n".join(lines)


def write_block(text: str, block: str) -> str:
    """Replace the generated block between the markers in *text*."""
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{HANDOFF} is missing the generated markers ({BEGIN} / {END})")
    head, _, rest = text.partition(BEGIN)
    _, _, tail = rest.partition(END)
    return f"{head}{BEGIN}\n{block}\n{END}{tail}"


def command_status(tickets: list[Ticket]) -> int:
    for ticket in tickets:
        flag = "STALE" if ticket.stale else ("?" if ticket.unknown else "ok")
        print(f"{flag:5} {ticket.ref:28} {ticket.status:16} {ticket.done_boxes}/{ticket.total_boxes}  {ticket.title}")
    return 0


def command_check(tickets: list[Ticket]) -> int:
    problems = [t for t in tickets if t.stale or t.unknown]
    for ticket in problems:
        reason = "all boxes ticked but status is still open" if ticket.stale else f"unknown status {ticket.status!r}"
        print(f"stale ticket: {ticket.ref} — {reason}", file=sys.stderr)
    if problems:
        print(f"{len(problems)} stale/unknown ticket(s); update Status before continuing.", file=sys.stderr)
        return 1
    print(f"tracker clean: {len(tickets)} ticket(s), {sum(t.open for t in tickets)} open")
    return 0


def command_write(tickets: list[Ticket], *, with_tests: bool) -> int:
    tests = _run_tests() if with_tests else None
    block = render_block(
        tickets,
        sha=_git("rev-parse", "--short", "HEAD"),
        subject=_git("log", "-1", "--pretty=%s"),
        today=date.today().isoformat(),
        tests=tests,
        active=active_milestone(),
    )
    text = HANDOFF.read_text(encoding="utf-8") if HANDOFF.is_file() else SCAFFOLD
    HANDOFF.write_text(write_block(text, block), encoding="utf-8")
    print(f"updated {HANDOFF}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("status", "check", "write"))
    parser.add_argument("--with-tests", action="store_true", help="Run pytest and record the result (write only).")
    args = parser.parse_args(argv)
    tickets = discover_tickets()
    if args.command == "status":
        return command_status(tickets)
    if args.command == "check":
        return command_check(tickets)
    return command_write(tickets, with_tests=args.with_tests)


if __name__ == "__main__":
    raise SystemExit(main())
